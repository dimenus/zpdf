//! Writes THIRD-PARTY-NOTICES.md: the notices of the third-party data and code built into
//! libzpdf and zpdf.wasm, each copied from the file it covers, so nothing is retyped.
//!
//!     gen-notices <out> <src/read_tables.zig> <kb LICENSE> <libdeflate COPYING> <src/cid/Adobe-*-UCS2 ...> -- <src/cmap/* ...>
//!
//! - Adobe's Core 14 AFM metrics and the Adobe Glyph List: read_tables.zig's `//!` header, which
//!   tools/gen-read-tables.py writes from the AFM files and keeps Adobe's notices and terms in.
//! - The Adobe Glyph List's BSD-3-Clause terms: glyphlist.txt is an input of gen-read-tables.py
//!   only, not in this repository; its terms are word for word the CMaps' below, with its own
//!   copyright line.
//! - Adobe's CID-to-Unicode CMaps: each file's `%%Copyright:` block.
//! - Adobe's predefined CMaps (src/cmap): their `%%Copyright:` blocks, each different block once,
//!   with the files that carry it.
//! - kb_text_shape: its LICENSE.
//! - libdeflate: its COPYING.
//!
//! `zig build notices` rewrites the file; `zig build test` fails when it differs from this output.

const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 6) {
        std.debug.print("usage: gen-notices <out> <read_tables.zig> <kb LICENSE> <libdeflate COPYING> <cmap>...\n", .{});
        std.process.exit(2);
    }
    const io = init.io;
    const cwd = std.Io.Dir.cwd();
    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;

    try w.writeAll(
        \\# Third-party notices
        \\
        \\zpdf is under the zlib licence (LICENSE). libzpdf, zpdf.wasm and the Zpdf NuGet package
        \\are built with the data and code below, under these terms.
        \\
        \\This file is generated by tools/gen-notices.zig from the files each section names.
        \\
        \\## Adobe Core 14 AFM metrics and the Adobe Glyph List
        \\
        \\In src/read_tables.zig: the standard fonts' widths, ascenders and descenders, and the glyph
        \\names, as that file's header says:
        \\
        \\```
        \\
    );
    const tables = try cwd.readFileAlloc(io, args[2], arena, .limited(1 << 24));
    var lines = std.mem.splitScalar(u8, tables, '\n');
    var header_lines: usize = 0;
    while (lines.next()) |line| {
        if (!std.mem.startsWith(u8, line, "//!")) break;
        const rest = line["//!".len..];
        const text = if (rest.len > 0 and rest[0] == ' ') rest[1..] else rest;
        try w.print("{s}\n", .{std.mem.trimEnd(u8, text, " ")});
        header_lines += 1;
    }
    if (header_lines < 10) fail("{s} has no notice header", .{args[2]});
    try w.writeAll("```\n\n");

    const sep = for (args[5..], 5..) |a, i| {
        if (std.mem.eql(u8, a, "--")) break i;
    } else fail("no -- before src/cmap's files", .{});
    const cmaps = args[5..sep];
    const encodings = args[sep + 1 ..];
    if (cmaps.len == 0 or encodings.len == 0) fail("no CMaps on one side of --", .{});
    // The glyph list's terms are the CMaps' terms: the first CMap's block after its copyright line.
    const first_block = try copyrightBlock(arena, io, cwd, cmaps[0]);
    const terms_at = std.mem.indexOf(u8, first_block, "\n\nRedistribution") orelse fail("{s}: no BSD terms", .{cmaps[0]});
    try w.print(
        \\The Adobe Glyph List (https://github.com/adobe-type-tools/agl-aglfn), whose glyph names are
        \\in src/read_tables.zig:
        \\
        \\```
        \\Copyright 2002-2019 Adobe (http://www.adobe.com/).
        \\{s}
        \\```
        \\
        \\
    , .{first_block[terms_at + 1 ..]});

    try w.writeAll(
        \\## Adobe CID-to-Unicode CMaps
        \\
        \\In src/cid, compiled into the text reader as lookup tables.
        \\
        \\
    );
    for (cmaps) |path| {
        try w.print("{s}:\n\n```\n{s}\n```\n\n", .{ std.fs.path.basename(path), try copyrightBlock(arena, io, cwd, path) });
    }

    try w.writeAll(
        \\## Adobe predefined CMaps
        \\
        \\In src/cmap (from https://github.com/adobe-type-tools/cmap-resources), compiled into the text
        \\reader as lookup tables. Each notice below is carried by the files listed before it.
        \\
        \\
    );
    var blocks: std.ArrayList(struct { text: []const u8, files: std.ArrayList([]const u8) }) = .empty;
    for (encodings) |path| {
        const block = try copyrightBlock(arena, io, cwd, path);
        for (blocks.items) |*b| {
            if (std.mem.eql(u8, b.text, block)) {
                try b.files.append(arena, std.fs.path.basename(path));
                break;
            }
        } else {
            var files: std.ArrayList([]const u8) = .empty;
            try files.append(arena, std.fs.path.basename(path));
            try blocks.append(arena, .{ .text = block, .files = files });
        }
    }
    for (blocks.items) |b| {
        for (b.files.items, 0..) |f, i| try w.print("{s}{s}", .{ if (i == 0) "" else ", ", f });
        try w.print(":\n\n```\n{s}\n```\n\n", .{b.text});
    }

    const kb = try cwd.readFileAlloc(io, args[3], arena, .limited(1 << 20));
    try w.print(
        \\## kb_text_shape
        \\
        \\The text shaper (https://github.com/JimmyLefevre/kb, built from the fork dimenus/kb):
        \\
        \\```
        \\{s}
        \\```
        \\
    , .{std.mem.trimEnd(u8, kb, "\n")});

    const libdeflate = try cwd.readFileAlloc(io, args[4], arena, .limited(1 << 20));
    try w.print(
        \\
        \\## libdeflate
        \\
        \\The DEFLATE decompressor (https://github.com/ebiggers/libdeflate, at the commit build.zig.zon pins):
        \\
        \\```
        \\{s}
        \\```
        \\
    , .{std.mem.trimEnd(u8, libdeflate, "\n")});

    try cwd.writeFile(io, .{ .sub_path = args[1], .data = out.written() });
}

/// A CMap's `%%Copyright:` lines between its two rules of dashes, without the prefix.
fn copyrightBlock(arena: std.mem.Allocator, io: std.Io, cwd: std.Io.Dir, path: []const u8) ![]const u8 {
    const text = try cwd.readFileAlloc(io, path, arena, .limited(1 << 24));
    var out: std.ArrayList(u8) = .empty;
    var rules: usize = 0;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trimEnd(u8, raw, "\r ");
        if (!std.mem.startsWith(u8, line, "%%Copyright:")) continue;
        const body = std.mem.trimStart(u8, line["%%Copyright:".len..], " ");
        if (std.mem.startsWith(u8, body, "-----")) {
            rules += 1;
            if (rules == 2) break;
            continue;
        }
        if (rules == 1) {
            if (out.items.len > 0) try out.append(arena, '\n');
            try out.appendSlice(arena, body);
        }
    }
    if (rules != 2 or std.mem.indexOf(u8, out.items, "Copyright") == null) fail("{s}: no %%Copyright block", .{path});
    return out.items;
}

fn fail(comptime fmt: []const u8, args: anytype) noreturn {
    std.debug.print("gen-notices: " ++ fmt ++ "\n", args);
    std.process.exit(1);
}
